"""Round 15 stage A: turn channels_plan.json into (1) worklist_r15a.py (named rows -> apply_hand_worklist.py, which adds
the e2m record and runs its checks) and (2) fill_r15a.json (empty-name rows: name + the default label as the map's old
label), with one role text per argument. Channel 15's two configs get the feature bit 4 off / on names, and its cache
(sensor_channel16_cached_axis_offset) is added. usage: make_worklist_r15a.py <plan.json> <worklist.py> <fill.json>"""
import json
import sys

plan_path, wl_path, fill_path = sys.argv[1:4]
SENSOR = {
    7: "the fuel temperature (e2m 1966 Fuel_Tmptr_Sensor; slot 7 = fuel_temperature_sensor_filtered)",
    8: "the remote accelerator pedal (e2m 1966 Remote_Throt_Sensor)",
    10: "the oil pressure (e2m 1966 Oil_Press_Sensor; slot 10 = oil_pressure_sensor_filtered)",
    13: "the accelerator pedal (e2m 1966 Sampled_Throt_Sensor; P2123 / P2122)",
    15: "the water in fuel sensor (e2m 1966 WIF_Sensor; P2267 / P2266)",
    21: "sensor reference voltage C (P0699 / P0698; e2m 1966 Throt_SV_Sensor, the throttle sensor supply)",
    28: "sensor reference voltage B (P0653 / P0652; e2m 1966 Engine_Conn_SV_Sensor)",
    42: "sensor reference voltage A (P0643 / P0642; e2m 1966 Supply_1_Volt_Sensor)",
    69: "the battery temperature (P0517 / P0516; e2m 1966 Battery_Tmptr_Sensor)",
    71: "the A/C refrigerant pressure (P0533 / P0532; e2m 1966 AC_Press_Sensor)",
    76: "the four wheel drive switch (P0839 / P0838; e2m 1966 Tcase_Mux_Sensor)",
    97: "accelerator pedal position sensor 1 (P2123 / P2122; e2m 1966 PPS_1_Throt_Sensor)",
    98: "accelerator pedal position sensor 2 (P2128 / P2127; e2m 1966 PPS_2_Throt_Sensor)",
    102: "the 48RE governor pressure (P0868 / P0869; e2m 1966 Trans_Gov_Press_Sensor)",
    105: "the EGR delta pressure (e2m 1966 EGR_Delta_Press_Sensor; faults 690 / 691)",
    108: "the EGR orifice temperature (e2m 1966 EGR_Orifice_Tmptr_Sensor; faults 796 / 797)",
}
ROLE = {
    0: "The sensor_channel_config_t of sensor channel {n}, {s}: argument 1 of its sensor channel calls",
    1: "The sensor_channel_state_t of sensor channel {n}, {s}: argument 2 of its sensor channel calls",
    2: "The lookup cache of sensor channel {n}'s linearization table, {s}: argument 3",
    6: "The EMA filter state of sensor channel {n}, {s}: argument 7",
    10: "The filtered engineering value of sensor channel {n}, {s}: the value output (argument 11)",
    11: "The default value of sensor channel {n}, {s}, used while its fault is confirmed: argument 12",
    12: "The fault status of sensor channel {n}, {s} (0 in range / 1 debouncing / 2 fault confirmed / 0x100 not "
        "enabled): argument 13",
}
TABLE_CHANNEL = {"egr_delta_pressure": 105, "egr_orifice_temperature": 108, "accelerator_pedal_position_sensor_1": 97,
                 "accelerator_pedal_position_sensor_2": 98, "water_in_fuel": 15}
plan = json.load(open(plan_path))
named, fill = [], []
for addr, old, new, empty, idx, chan in plan:
    if addr == "0x003fefca":
        new = "water_in_fuel_sensor_feature_bit_4_off_config"
    elif addr == "0x003fefda":
        new = "water_in_fuel_sensor_feature_bit_4_on_config"
    if idx == "table":
        base = next(k for k in TABLE_CHANNEL if new.startswith(k + "_"))
        n = TABLE_CHANNEL[base]
        role = (f"The linearization {'axis' if new.endswith('_axis') else 'values'} of sensor channel {n}, "
                f"{SENSOR[n]}")
    else:
        role = ROLE[idx].format(n=chan, s=SENSOR[chan])
    if addr in ("0x003fefca", "0x003fefda"):
        role += " (its feature bit 4 " + ("off" if addr == "0x003fefca" else "on") + " calls)"
    (fill if empty else named).append((addr, old, new, role))
named.append(("0x003fa0ba", "sensor_channel16_cached_axis_offset", "water_in_fuel_linearization_cached_axis_offset",
              "The lookup cache of sensor channel 15's linearization tables (both feature bit 4 variants), "
              + SENSOR[15] + ": argument 3"))
with open(wl_path, "w") as f:
    f.write('"""Round 15 stage A (label-only): the sixteen sensor channels e2m 1966 names, as families - generated by '
            'make_worklist_r15a.py from the sensor channel calls (channel_index = argument 8)."""\n')
    f.write("GLOBALS = [\n")
    for addr, old, new, role in named:
        f.write(f"    ({addr!r}, {new!r},\n     {role!r}),\n")
    f.write("]\nFUNCTIONS = []\n")
json.dump(fill, open(fill_path, "w"), indent=0)
print(f"{len(named)} named rows, {len(fill)} empty rows to fill")
