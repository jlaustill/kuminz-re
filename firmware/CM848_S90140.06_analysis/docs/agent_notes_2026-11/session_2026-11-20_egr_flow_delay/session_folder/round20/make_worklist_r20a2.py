"""Round 20 stage A, part 2: generate worklist_r20a2.py - every word of the algorithm enable flags block (e2m 106B; RAM
0x3fd59a + offset = EEPROM 0x118 + offset; the e2m's 'word N' is at offset 2 + 2N, e.g. [FSUCFLEN] 'Bit 0 Word 4' at
+A) whose row has a guessed name gets algorithm_enable_flags_<N>_cal, with its e2m bits (name and mask) in the comment.
The alignment was checked against code uses: word 29 0x100 DM13 (cm848_processJ1939Dm13StopStartBroadcast), 0x20 /
0x40 trip / service reset (cm848_j1939HandlePgn56832Reset), 0x800 throttle error handler
(cm848_checkAcceleratorPedalSensorFaults); word 28 0x400 J1939_Multiplex_Enable (the J1939 input layer).
usage: make_worklist_r20a2.py <repo> <out.py>"""
import collections
import os
import sys

repo, out_path = os.path.abspath(sys.argv[1]), sys.argv[2]
BASE = 0x3fd59a
recs = collections.defaultdict(list)
for line in open(os.path.join(repo, "e2m-analysis/CHR/CHR_CC_11.45.01.07.e2m"), errors="replace"):
    f = line.split(";")[0].split(",")
    if len(f) > 10 and f[2] == "106B":
        recs[int(f[3], 16)].append((int(f[10], 16), f[0]))
rows = {}
for l in open(os.path.join(repo, "firmware/CM848_S90140.06_analysis/output/global_variables.csv")):
    if l.startswith("0x"):
        a = int(l[:10], 16)
        if BASE <= a < BASE + 0x60:
            rows[a] = l.split(",", 3)[1]
out = ['"""Round 20 stage A, part 2 (label-only): the algorithm enable flags words with guessed names, named by their e2m '
       '106B word number - generated by make_worklist_r20a2.py."""', "GLOBALS = ["]
n = 0
for a in sorted(rows):
    off = a - BASE
    name = rows[a]
    if name.startswith("algorithm_enable_flags_") or off < 2 or not recs.get(off):
        continue
    word = (off - 2) // 2
    bits = ", ".join(f"0x{m:x} {nm}" for m, nm in sorted(recs[off]))
    role = (f"Algorithm enable flags word {word} (EEPROM 0x{0x118 + off:x}, in the CRC-guarded block; e2m 106B +{off:X}): "
            f"{bits}")
    out.append(f"    ({f'0x{a:08x}'!r}, {f'algorithm_enable_flags_{word}_cal'!r},\n     {role!r}),")
    n += 1
out.append("]\nFUNCTIONS = []\n")
open(out_path, "w").write("\n".join(out))
print(n, "words")
